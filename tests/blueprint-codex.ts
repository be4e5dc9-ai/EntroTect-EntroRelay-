import assert from 'node:assert/strict';
import test from 'node:test';
import os from 'node:os';
import path from 'node:path';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import { Store, atomicJson } from '../backend/store';
import { SettingsStore, defaultAgentConnection } from '../backend/settings';
import { Controller } from '../backend/controller';
import { HistoryService } from '../backend/history';
import { HistorySync } from '../backend/history-sync';
import { bridgeEntries, messagesToBridge, portableMessages } from '../backend/portable-history';

test('Codex shares the manual mapping across restart and keeps a conflicting branch separate',{timeout:120_000},async()=>{
  const root = await mkdtemp(path.join(os.tmpdir(),'entrotect-codex-sync-'));
  const home = path.join(root,'standalone'), cwd = path.join(root,'project');
  await Promise.all([mkdir(home),mkdir(cwd)]);
  const store = new Store(path.join(root,'desktop'));
  await store.init();
  const settings = new SettingsStore(store.root,path.resolve('.runtime'),process.execPath,{protect:async s=>s,unprotect:async s=>s});
  await settings.init();
  settings.value.agents = {...settings.value.agents,codex:{...defaultAgentConnection('codex'),home,isolatedNative:true}};
  const controller = new Controller(store,settings,()=>{});
  const history = new HistoryService(controller);
  const target = {harness:'codex' as const,location:home};
  let sync = new HistorySync(controller,history,()=>{},async()=>({}));
  try {
    await sync.init();
    const chat = await controller.create(cwd,'codex',target);
    chat.title = 'Shared chat';
    chat.revision = 1;
    chat.canonicalPath = path.join(store.directory(chat.id),'context','fixture.entrotect.json');
    const time = Date.now();
    await atomicJson(chat.canonicalPath,messagesToBridge([{role:'user',text:'cross-profile fixture',time}],{id:chat.id,title:chat.title,cwd,createdAt:time,updatedAt:time}));
    await store.save(chat);
    assert.equal((await history.list(target)).sessions.length,0);
    const request = {conversationId:chat.id,target};
    const first = await sync.exportManually(request);
    assert.equal((await sync.exportManually(request)).sessionId,first.sessionId);
    await sync.stop();
    sync = new HistorySync(controller,history,()=>{},async()=>({}));
    await sync.init();
    await sync.blueprint.setRule(sync.blueprint.scope(chat)!,target.harness,true);
    await sync.blueprint.setRule({source:target,workspace:cwd},target.harness,true);
    assert.deepEqual((await sync.run(true)).issues,[]);
    assert.equal((await sync.exportManually(request)).sessionId,first.sessionId);
    assert.deepEqual((await history.list(target)).sessions.map(s=>s.id),[first.sessionId]);
    assert.equal(store.list().length,1);
    const native=await controller.agents.read('codex',home,cwd,first.sessionId);
    chat.revision++;
    await atomicJson(chat.canonicalPath,messagesToBridge([...native.history,{role:'user',text:'desktop continuation',time}],{id:chat.id,title:chat.title,cwd,createdAt:time,updatedAt:time}));
    await store.save(chat);
    await controller.agents.append(chat,'codex',home,first.sessionId,native.version,[...native.history,{role:'user',text:'standalone continuation',time}],async()=>{});
    assert.deepEqual((await sync.run(true)).issues,[]);
    const [conflict]=sync.conflicts();
    assert.deepEqual(conflict.local,['user desktop continuation']);
    assert.deepEqual(conflict.remote,['user standalone continuation']);
    await sync.resolveConflict(conflict.id,'both');
    assert.deepEqual((await sync.run(true)).issues,[]);
    const branch=store.list().find(c=>c.id!==chat.id)!;
    assert.deepEqual(branch.origin?.source,target);
    assert.equal(branch.origin?.sessionId,undefined);
    assert.equal(branch.bindings.codex,undefined);
    const archived=portableMessages(bridgeEntries(JSON.parse(await readFile(branch.canonicalPath!,'utf8')),'archive'));
    assert(archived.some(e=>e.text==='standalone continuation'));
    const resolved=await controller.agents.read('codex',home,cwd,first.sessionId);
    assert(resolved.archived.some(e=>e.text==='desktop continuation'));
    assert(!resolved.archived.some(e=>e.text==='standalone continuation'));
    assert.deepEqual((await history.list(target)).sessions.map(s=>s.id),[first.sessionId]);
  } finally { await sync.stop(); await controller.close(); await rm(root,{recursive:true,force:true,maxRetries:5,retryDelay:100}); }
});
