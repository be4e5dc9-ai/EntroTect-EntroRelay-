import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdir,writeFile,symlink,unlink} from 'node:fs/promises';
import path from 'node:path';
import {WorkspaceService} from '../backend/workspace';
const run=promisify(execFile),service=new WorkspaceService();
const base=path.resolve('.local',`workspace-service-${Date.now()}`),root=path.join(base,'project with spaces'),outside=path.join(base,'outside');
process.env.GIT_CEILING_DIRECTORIES=base;
await mkdir(path.join(root,'src'),{recursive:true});await mkdir(outside,{recursive:true});
await writeFile(path.join(outside,'private.txt'),'OUTSIDE');
const git=(...args:string[])=>run('git',['-C',root,...args],{windowsHide:true});
assert.equal((await service.status(root)).repository,false);
await git('init');await git('config','user.name','Local Test');await git('config','user.email','test@example.invalid');
await writeFile(path.join(root,'src','旧 名称.ts'),'export const value = 1;\n');
await writeFile(path.join(root,'delete.txt'),'DELETE_ME\n');
await writeFile(path.join(root,'sibling.txt'),'before\n');
await git('add','.');await git('commit','-m','initial');
await git('mv','src/旧 名称.ts','src/新 名称.ts');
await writeFile(path.join(root,'src','新 名称.ts'),'export const value = 2;\n');
await unlink(path.join(root,'delete.txt'));
await writeFile(path.join(root,'sibling.txt'),'after\n');
await writeFile(path.join(root,'-new file.txt'),'NEW_MARKER\n');
await writeFile(path.join(root,'empty.txt'),'');
await writeFile(path.join(root,'binary.dat'),Buffer.from([0,1,2,255]));
const listing=await service.files(root);assert(!listing.entries.some(entry=>entry.name==='.git'));assert.equal(listing.entries[0].kind,'directory');
const status=await service.status(root);assert(status.repository);assert(status.branch);
const renamed=status.changes.find(change=>change.path==='src/新 名称.ts');assert.equal(renamed?.oldPath,'src/旧 名称.ts');assert.equal(renamed?.index,'R');assert.equal(renamed?.worktree,'M');
const diff=await service.diff(root,'src/新 名称.ts');assert(diff.staged.includes('value = 1'));assert(diff.unstaged.includes('-export const value = 1'));assert(diff.unstaged.includes('+export const value = 2'));
assert((await service.diff(root,'delete.txt')).unstaged.includes('-DELETE_ME'));
assert((await service.diff(root,'-new file.txt')).unstaged.includes('+NEW_MARKER'));
assert(!(await service.diff(root,'empty.txt')).unstaged.includes('@@'));
assert.equal((await service.read(root,'binary.dat')).binary,true);
const pixel = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNgYAAAAAMAASsJTYQAAAAASUVORK5CYII=', 'base64');
await writeFile(path.join(root,'image.png'),pixel);
assert.deepEqual((await service.read(root,'image.png')).image,{mime:'image/png',base64:pixel.toString('base64')});
assert.equal((await service.read(root,'image.png',false)).image,undefined);
await writeFile(path.join(root,'text.png'),'text with an image extension');
assert.equal((await service.read(root,'text.png')).text,'text with an image extension');
await writeFile(path.join(root,'utf16.txt'),Buffer.from('\ufeff双字\r\n','utf16le'));
assert.equal((await service.read(root,'utf16.txt')).text,'双字\n');
await writeFile(path.join(root,'large.txt'),'a'.repeat(700000));assert.equal((await service.read(root,'large.txt')).truncated,true);
await assert.rejects(service.read(root,'../outside/private.txt'));
await assert.rejects(service.read(root,path.join(outside,'private.txt')));
await symlink(outside,path.join(root,'linked-outside'),'junction');
await assert.rejects(service.read(root,'linked-outside/private.txt'));
assert.equal((await service.readReference(root,{path:path.join(root,'src','新 名称.ts'),line:1})).path,'src/新 名称.ts');
await assert.rejects(service.readReference(root,{path:'../outside/private.txt'}), /只能预览当前项目/);
await assert.rejects(service.readReference(root,{path:path.join(root,'linked-outside','private.txt')}), /目录之外/);
assert.equal((await service.files(root)).entries.find(entry=>entry.name==='linked-outside')?.kind,'link');
const nested=await service.status(path.join(root,'src'));assert(nested.changes.every(change=>!change.path.startsWith('../')));assert(!nested.changes.some(change=>change.path==='sibling.txt'));
console.log('WORKSPACE_SERVICE_OK',root);
