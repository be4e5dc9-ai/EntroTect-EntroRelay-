import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { atomicJson } from '../backend/store';
import { modelFixture } from './fixture-server';
import { launchTauri } from './tauri-launch';

test('blueprint publishes and reuses one native history across desktop restart', async () => {
  const fixture = await modelFixture(), root = path.resolve('.local', `history-e2e-${Date.now()}`);
  const workspace = path.join(root, 'project'), external = path.join(root, 'standalone-dsh');
  await mkdir(workspace, { recursive: true }); await mkdir(path.join(external, 'sessions'), { recursive: true });
  await atomicJson(path.join(root, 'settings.json'), { defaultWorkspace: workspace, deepseek: { executable: '@bundled/node', args: ['@bundled/deepseek', '--profile', 'sdk'], home: external, provider: 'deepseek-official', model: 'deepseek-flash', authMode: 'api', baseUrl: fixture.origin } });
  const launch = () => launchTauri({ ...process.env, ENTROTECT_DATA_DIR: root });
  let desktop = await launch();
  try {
    let page = await desktop.firstWindow();
    await page.evaluate(async () => { const b = await window.entrotect!.bootstrap(); await window.entrotect!.saveSettings(b.settings, { deepseek: 'local-fixture-only' }); });
    await page.getByRole('textbox', { name: '任务输入' }).fill('请记住迁移标记 ALPHA-731'); await page.getByRole('button', { name: '发送任务', exact: true }).click();
    await expect(page.getByRole('status', { name: '运行状态' })).toHaveText('就绪');
    await page.getByTitle('会话菜单', { exact: true }).click();
    await page.getByRole('menuitem', { name: '设置对话同步' }).click();
    const graph = page.getByRole('main', { name: '同步蓝图' });
    await expect(graph.getByRole('region', { name: '连接详情' })).toContainText('ALPHA-731');
    const deepseekCard = graph.locator('#bp-source-deepseek');
    const codex = graph.locator('[data-sender="codex"]'), codexCard = graph.locator('#bp-source-codex');
    await expect(deepseekCard).toBeVisible();
    await codex.click();
    await expect(codexCard.locator('.bp-location')).toBeVisible();
    await expect(deepseekCard).toBeVisible();
    const offsets = await graph.evaluate(element=>['deepseek','codex'].map(harness=>{
      const node=element.querySelector(`[data-sender="${harness}"]`)!.getBoundingClientRect();
      const card=element.querySelector('#bp-source-'+harness)!.getBoundingClientRect();
      return [Math.round(card.left-node.right),Math.round(card.top-node.top)];
    }));
    expect(offsets[1]).toEqual(offsets[0]);
    expect(offsets[0][0]).toBeGreaterThan(0);
    expect(offsets[0][1]).toBe(0);
    await codex.click();
    await expect(codexCard).toBeHidden();
    await expect(deepseekCard).toBeVisible();
    const receiver = graph.locator('[data-receiver="deepseek"]');
    const beforeMove = (await receiver.boundingBox())!;
    await page.mouse.move(beforeMove.x+45,beforeMove.y+16);
    await page.mouse.down();
    await page.mouse.move(beforeMove.x-5,beforeMove.y+29,{steps:6});
    await page.mouse.up();
    await expect.poll(async()=>Math.round((await receiver.boundingBox())!.x-beforeMove.x)).toBe(-50);
    expect((await page.evaluate(()=>window.entrotect!.blueprint())).rules).toHaveLength(0);
    await receiver.click();
    await expect(graph.locator('footer[role="status"]')).toContainText('已连接到');
    await graph.getByRole('button', { name: '立即同步', exact: true }).click();
    await expect(graph.locator('footer[role="status"]')).toHaveText('已检查已连接的项目和对话');
    const nativeSource = { harness: 'deepseek', location: external } as const;
    const history = () => page.evaluate(source => window.entrotect!.listHistory(source), nativeSource);
    const initial = (await history()).sessions;
    expect(initial).toHaveLength(1);
    expect(initial[0].title).toContain('ALPHA-731');
    await graph.screenshot({ path: '.local/screenshots/history-export.png' });
    await graph.getByTitle('返回工作区').click();
    fixture.reply('继续成功 BETA-842');
    await page.getByRole('textbox', { name: '任务输入' }).fill('核对历史并记住 BETA-842');
    await page.getByRole('button', { name: '发送任务', exact: true }).click();
    await expect(page.getByRole('status', { name: '运行状态' })).toHaveText('就绪');
    await expect(page.locator('.message.assistant').last()).toContainText('BETA-842');
    expect(JSON.stringify(fixture.requests.at(-1)!.body.messages)).toContain('ALPHA-731');
    await page.getByTitle('导入历史对话', { exact: true }).click();
    await graph.getByRole('button', { name: '立即同步', exact: true }).click();
    await expect(graph.locator('footer[role="status"]')).toHaveText('已检查已连接的项目和对话');
    expect((await history()).sessions.map(row => row.id)).toEqual([initial[0].id]);
    const saved = JSON.parse(await readFile(path.join(root, 'conversations.json'), 'utf8'));
    expect(saved).toHaveLength(1);
    expect(saved[0].revision).toBe(2);
    await desktop.close(); desktop = await launch(); page = await desktop.firstWindow(); await page.locator('.conversation-row').first().click();
    await expect(page.locator('.message.assistant').last()).toContainText('BETA-842');
  } finally { await desktop.close(); await fixture.close(); }
});
